(function () {
  const host = document.getElementById('fact-list');
  if (!host) return;
  const LABEL = { ok: '已核對', diff: '說法不一', todo: '待查證' };
  const groups = [];
  window.FACTS.forEach((r) => {
    let g = groups.find((x) => x.item === r.item);
    if (!g) groups.push(g = { item: r.item, rows: [] });
    g.rows.push(r);
  });
  const n = (s) => window.FACTS.filter((r) => r.status === s).length;
  host.innerHTML = `<p class="fact-count">共 ${window.FACTS.length} 項：<b>${n('ok')}</b> 項已核對、<b>${n('diff')}</b> 項說法不一、<b>${n('todo')}</b> 項待查證</p>` +
    groups.map((g) => `
      <section class="fact-group"><h2>${esc(g.item)}</h2>
        ${g.rows.map((r) => `<div class="fact-row">
          <span class="st ${r.status}">${LABEL[r.status]}</span>
          <div><p class="fact-claim">${esc(r.claim)}</p>
            ${r.note ? `<p class="fact-note">${esc(r.note)}</p>` : ''}
            ${r.src.length ? `<p class="fact-src">出處：${r.src.map(([t, u]) => `<a href="${esc(u)}" target="_blank" rel="noopener">${esc(t)}</a>`).join('、')}</p>` : ''}
          </div></div>`).join('')}
      </section>`).join('');
})();
