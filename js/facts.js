  "note": "維基共享資源與維基百科都找不到這兩個型號的可用照片，所以目前仍用原本的圖，來源與授權不明。SC-1000 那張是同時期的 SH-100S，不是 SC-1000 本身。需要換成有授權的圖，或自行拍攝／取得授權。",
